"""
Claude Code IDE integration.

Generates CLAUDE.md configuration for Claude Code CLI.
"""

from pathlib import Path
from typing import Dict, Any, Optional

from .base import IDEIntegration


class ClaudeCodeIntegration(IDEIntegration):
    """Claude Code integration."""

    @property
    def name(self) -> str:
        return "Claude Code"

    @property
    def config_file_path(self) -> Path:
        return self.spoke_dir / 'CLAUDE.md'

    def detect(self) -> bool:
        """
        Detect if Claude Code is being used.

        Checks for:
        - .claude/ directory
        - CLAUDE.md file
        - $CLAUDE_CLI environment variable
        """
        has_claude_dir = (self.spoke_dir / '.claude').exists()
        has_claude_md = self.config_file_path.exists()

        import os
        has_env_var = os.environ.get('CLAUDE_CLI') is not None

        return has_claude_dir or has_claude_md or has_env_var

    def get_capabilities(self) -> Dict[str, Any]:
        """Get Claude Code capabilities."""
        return {
            'supports_custom_instructions': True,
            'supports_file_watching': True,
            'supports_hooks': True,
            'supports_mcp_servers': True,
            'supports_tool_use': True,
            'context_window': 200000,  # Claude Sonnet 4.5
            'supports_images': True,
            'supports_pdfs': True
        }

    def generate_config(self, template_vars: Optional[Dict[str, Any]] = None) -> str:
        """Generate CLAUDE.md configuration."""

        # Read WAI-State.json for project info
        state_file = self.wai_spoke_dir / 'WAI-State.json'
        import json
        state = {}
        if state_file.exists():
            with open(state_file) as f:
                state = json.load(f)

        project_name = state.get('wheel', {}).get('name', 'Project')
        project_description = state.get('wheel', {}).get('description', '')

        template_path = self.spoke_dir / 'templates' / 'claude' / 'CLAUDE.md'
        if project_name == "Wheelwright Framework" and template_path.exists():
            template_content = template_path.read_text()
            return (
                template_content
                .replace('{{PROJECT_NAME}}', project_name)
                .replace('{{PROJECT_DESCRIPTION}}', project_description)
            )

        # Fallback to minimal config for other projects
        config = f"""# Claude Code Instructions for {project_name}

**CRITICAL: This project uses Wheelwright for session continuity.**

## Priority 0: Session Start Protocol

When you first receive a message in this project directory, execute the session start protocol:

1. **Load WAI Context**:
   - Read `WAI-Spoke/WAI-Guide.md` (full AI instructions)
   - Read `WAI-Spoke/WAI-State.json` (project state, decisions)
   - Read `WAI-Spoke/WAI-State.md` (strategic vision)

2. **Brief the User**:
   - Project: {project_name}
   - Last session info from WAI-State.json
   - Current phase and next actions

3. **Check Uncommitted Work**:
   - Run `git status`
   - If uncommitted changes, ask if resuming previous session or starting fresh

## Priority 1: Behavioral Guidelines

Follow the guidelines in `WAI-Spoke/WAI-Guide.md` for:
- Stewardship philosophy (AI as responsible partner)
- Session state management
- High-impact decision logging (impact >= 8)
- Conversation logging to WAI-Session-Log.jsonl

### Conversation Logging
Log every user and assistant turn to `WAI-Spoke/WAI-Session-Log.jsonl`.
Hub learning cannot proceed until Closeout processes and clears the log.

### Complexity Gate (Planning Required)
Assess task complexity before acting.

If the task affects 2+ files or requires 6+ steps:
- Stay in discussion mode until the user says "READY TO PLAN"
- Propose a structured plan
- Wait for "PLAN ACCEPTED" before implementation

### PRIORITY 1.5: TOKEN EFFICIENCY
Assess task complexity before acting. Use ADAPTIVE workflow when needed.

## Priority 2: Session Commands

### 'Time'
Check token usage and context capacity.

### 'Compact'
Command: 'Compact'
Compress context by summarizing resolved discussions.

### 'Closeout'
Command: 'Closeout'
End session with smart processing:
- Scan WAI-Spoke/ for unknown files
- Reconcile hub learnings
- Rebalance file content
- Extract signals
- Update analytics
- Clear logs

### 'Shipit'
Command: 'Shipit'
Closeout + git commit in one command.

## Project Context

{project_description}

**See WAI-Spoke/ for complete project context and instructions.**

---

*This file was auto-generated by Wheelwright IDE integration.*
*To update: `WAI-CLI configure-ide --force`*
"""

        return config

    def write_config(self, content: Optional[str] = None) -> Path:
        """Write CLAUDE.md to project root."""
        if content is None:
            content = self.generate_config()

        self.config_file_path.write_text(content)
        return self.config_file_path
